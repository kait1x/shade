#!/usr/bin/env bash
set -e

CYAN='\033[0;36m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# ── Check Docker ──────────────────────────────────────
if ! command -v docker &>/dev/null; then
  echo -e "${RED}Ошибка: Docker не найден. Установите Docker и повторите.${NC}"
  exit 1
fi
if ! command -v docker compose &>/dev/null; then
  echo -e "${RED}Ошибка: Docker Compose не найден. Установите docker compose.${NC}"
  exit 1
fi
echo -e "${GREEN}✓ Docker и Docker Compose найдены${NC}"

# ── Create .env if missing ───────────────────────────
ENV_FILE="${SCRIPT_DIR}/.env"
if [ ! -f "$ENV_FILE" ]; then
  DASHBOARD_PASS=$(openssl rand -base64 12 | tr -d '\n')
  SESSION_SECRET=$(openssl rand -base64 24 | tr -d '\n')

  cat > "$ENV_FILE" <<EOF
# Auto-generated by deploy.sh — $(date -u '+%Y-%m-%d %H:%M UTC')
DASHBOARD_PASS=${DASHBOARD_PASS}
SESSION_SECRET=${SESSION_SECRET}
ALLOWED_ORIGINS=http://localhost:3000
EOF
  chmod 600 "$ENV_FILE"
  echo -e "${GREEN}✓ Создан .env с паролем и сессией${NC}"
else
  echo -e "${YELLOW}ℹ .env уже существует — используется существующий${NC}"
  # Ensure DASHBOARD_PASS is set
  if ! grep -q "^DASHBOARD_PASS=" "$ENV_FILE"; then
    DASHBOARD_PASS=$(openssl rand -base64 12 | tr -d '\n')
    echo "DASHBOARD_PASS=${DASHBOARD_PASS}" >> "$ENV_FILE"
  fi
fi

# ── Create certs dir ──────────────────────────────────
CERTS_DIR="${SCRIPT_DIR}/server/certs"
DATA_DIR="${SCRIPT_DIR}/server/data"
mkdir -p "$CERTS_DIR" "$DATA_DIR"

# ── Build & start ─────────────────────────────────────
cd "$SCRIPT_DIR"
echo -e "${CYAN}▶ Собираем и запускаем контейнеры...${NC}"
docker compose up -d --build

# ── Wait for healthy container ────────────────────────
echo -e "${CYAN}▶ Ожидаем запуска сервера...${NC}"
sleep 5

# Read password from .env
DASHBOARD_PASS=$(grep "^DASHBOARD_PASS=" "$ENV_FILE" | cut -d'=' -f2)

echo ""
echo -e "${GREEN}╔══════════════════════════════════════════════════╗${NC}"
echo -e "${GREEN}║  Shade сервер успешно запущен!                     ║${NC}"
echo -e "${GREEN}╠══════════════════════════════════════════════════╣${NC}"
echo -e "${GREEN}║  Админ-панель:  https://localhost:3443/dashboard   ║${NC}"
echo -e "${GREEN}║  API:           https://localhost:3443/api          ║${NC}"
echo -e "${GREEN}║  HTTP→HTTPS:    http://localhost:3000  (редирект)   ║${NC}"
echo -e "${GREEN}╠══════════════════════════════════════════════════╣${NC}"
echo -e "${YELLOW}║  Пароль: ${DASHBOARD_PASS}${NC}"
echo -e "${GREEN}╚══════════════════════════════════════════════════╝${NC}"
echo ""
echo "Логи: docker compose logs -f shade-server"
echo "Остановка: docker compose down"