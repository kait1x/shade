import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { randomBytes } from 'node:crypto';
import { io } from 'socket.io-client';
import { fixture, identity, register, operation, proof, trust } from './helpers/alpha-fixture.mjs';
import { sealMessage, openMessage, approveDevices, pairingProof } from '../../client/web/device_crypto.mjs';

test('isolated HTTP + real WebSocket: E2EE, device ACK, replay, ownership, restart and immutable retry', { timeout: 180000 }, async t => {
  await fs.mkdir(path.resolve('build'), { recursive: true });
  const dataDir = await fs.mkdtemp(path.resolve('build/alpha-transport-'));
  const storageSecret = randomBytes(32).toString('hex');
  let f = await fixture({ dataDir, storageSecret });
  const sockets = [];
  t.after(async () => { sockets.forEach(s => s.disconnect()); await f.close(); });
  const alice = await identity('http_alice'), bob = await identity('http_bob');
  let ac = await f.login('synthetic-alice'), bc = await f.login('synthetic-bob');
  await register(f, alice, ac); await register(f, bob, bc);
  assert.equal((await f.request('/api/v2/operation', { op: 'fetch' })).response.status, 401);
  const bad = await f.request('/api/v2/challenge', { account: 'http_alice', id: alice.session.id, operation: '0'.repeat(64) }, bc);
  assert.equal(bad.response.status, 400);
  const socket = io(f.origin, { transports: ['websocket'], autoConnect: false, reconnection: false,
    extraHeaders: { Cookie: bc }, auth: await proof(f, bob, bc, 'socket') }); sockets.push(socket);
  await new Promise((resolve, reject) => { socket.once('connect', resolve); socket.once('connect_error', reject); socket.connect(); });
  assert.equal(socket.io.engine.transport.name, 'websocket');
  const text = 'HTTP настоящая проверка E2EE 🔐';
  const message = await sealMessage(text, [alice.manifest], [bob.manifest], alice.session, trust(alice,bob));
  const ref = `${message.from}:${message.deviceId}:${message.id}`;
  const hinted = new Promise(resolve => socket.once('inbox', resolve));
  const sent = await operation(f, alice, ac, 'send', message); assert.equal(sent.result.accepted, true); await hinted;
  assert.ok(!JSON.stringify(f.registry.exportSnapshot()).includes(text));
  const status = await operation(f, alice, ac, 'status', [ref]);
  assert.equal(status.result[ref][0].acknowledgedAt, null, 'server acceptance and socket hint are not delivery');
  const auth = await proof(f, bob, bc, 'fetch');
  const inbox = await f.request('/api/v2/operation', { op: 'fetch', auth }, bc);
  assert.equal(await openMessage(inbox.result[0], bob.session, trust(alice,bob)), text);
  assert.equal((await f.request('/api/v2/operation', { op: 'fetch', auth }, bc)).response.status, 400, 'proof replay');
  const altered = structuredClone(inbox.result[0]); altered.message.envelopes[0].payload.d = 'A'.repeat(altered.message.envelopes[0].payload.d.length);
  await assert.rejects(openMessage(altered, bob.session, trust(alice,bob)));
  const ack = await proof(f, bob, bc, 'ack', [ref]); ack.proof = 'AAAA';
  assert.equal((await f.request('/api/v2/operation', { op: 'ack', body: [ref], auth: ack }, bc)).response.status, 400);
  assert.equal((await operation(f, alice, ac, 'status', [ref])).result[ref][0].acknowledgedAt, null);
  assert.equal((await operation(f, bob, bc, 'ack', [ref])).result.acknowledged, 1);
  assert.ok((await operation(f, alice, ac, 'status', [ref])).result[ref][0].acknowledgedAt > 0);
  const renewal = await approveDevices(alice.genesis, [alice.manifest], alice.manifest.devices, alice.session);
  assert.equal((await operation(f, alice, ac, 'install', { manifest: renewal })).response.status, 200);
  assert.equal((await operation(f, alice, ac, 'send', message)).result.duplicate, true, 'retry after lease renewal');
  const encoded = await fs.readFile(path.join(dataDir, 'device-v2.enc'), 'utf8');
  assert.ok(!encoded.includes('http_alice') && !encoded.includes(text));
  socket.disconnect(); await f.close();
  f = await fixture({ dataDir, storageSecret }); ac = await f.login('synthetic-alice'); bc = await f.login('synthetic-bob');
  assert.equal((await operation(f, bob, bc, 'fetch')).result.length, 0, 'ACK survives restart');
  assert.equal((await operation(f, alice, ac, 'send', message)).result.duplicate, true);
  const reverse = await sealMessage('HTTP ответ после перезапуска', [bob.manifest], [alice.manifest,renewal], bob.session, trust(bob,alice));
  assert.equal((await operation(f, bob, bc, 'send', reverse)).response.status, 200);
  const received = (await operation(f, alice, ac, 'fetch')).result.find(b => b.message.id === reverse.id);
  assert.equal(await openMessage(received, alice.session, trust(bob,alice)), 'HTTP ответ после перезапуска');
  const evil = await f.request('/api/v2/challenge', { account:'http_alice',id:alice.session.id,operation:'0'.repeat(64) }, ac);
  assert.equal(evil.response.status, 200);
  assert.equal((await f.request('/auth/google/callback?state=bad&code=synthetic-attacker')).response.status, 400);
  assert.equal((await f.request('/api/v2/register', { genesis: alice.genesis, manifest: alice.manifest, proofs:[await pairingProof(alice.vault,alice.session)] }, ac)).response.status, 409);
});
